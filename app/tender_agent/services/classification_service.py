from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from uuid import UUID

from app.tender_agent.domain.classification import (
    DocumentClassificationDecision,
    PageClassificationDecision,
    TenderDocumentType,
)


@dataclass(frozen=True)
class ClassificationLimits:
    probe_characters: int = 4000
    minimum_confidence: float = 0.60


class TenderClassificationService:
    def __init__(
        self,
        limits: ClassificationLimits,
    ) -> None:
        self.limits = limits

    def classify_page(
        self,
        *,
        page_id: UUID,
        page_number: int,
        source_name: str,
        text: str,
    ) -> PageClassificationDecision:
        probe = text[: self.limits.probe_characters]

        normalized_name = self._normalize(
            Path(source_name).name
        )
        normalized_text = self._normalize(probe)

        heading_lines = [
            self._normalize(line)
            for line in probe.splitlines()[:24]
            if self._normalize(line)
        ]

        heading_probe = "\n".join(heading_lines[:12])
        haystack = f"{normalized_name}\n{normalized_text}"

        strong_result = self._classify_strong_heading(
            heading_probe=heading_probe,
            page_id=page_id,
            page_number=page_number,
            source_name=source_name,
        )

        if strong_result is not None:
            return strong_result

        rules: list[
            tuple[
                TenderDocumentType,
                list[str],
                float,
                str,
            ]
        ] = [
            (
                "corrigendum",
                [
                    "corrigendum",
                    "addendum",
                    "tender amendment",
                    "amendment to tender",
                    "amendment to rfp",
                ],
                0.90,
                "Matched corrigendum or amendment signals.",
            ),
            (
                "prebid_clarification",
                [
                    "pre bid clarification",
                    "pre bid queries",
                    "reply to pre bid queries",
                    "response to pre bid queries",
                    "pre bid meeting",
                ],
                0.90,
                "Matched pre-bid clarification signals.",
            ),
            (
                "gem_bid",
                [
                    "gem bidding",
                    "gem bid document",
                    "bid number",
                    "generated by gem",
                ],
                0.85,
                "Matched GeM bid-document signals.",
            ),
            (
                "tender_notice",
                [
                    "notice inviting tender",
                    "invitation for bids",
                    "invitation to tender",
                    "tender notice",
                    "nit number",
                ],
                0.85,
                "Matched tender-notice signals.",
            ),
            (
                "atc_stc_sla_gtc",
                [
                    "buyer added bid specific terms",
                    "additional terms and conditions",
                    "special terms and conditions",
                    "general terms and conditions",
                    "service level agreement",
                ],
                0.82,
                "Matched ATC, STC, SLA or GTC signals.",
            ),
            (
                "technical_specs_or_sow",
                [
                    "technical specification",
                    "scope of work",
                    "statement of work",
                    "technical requirements",
                    "technical data sheet",
                    "deliverables",
                ],
                0.82,
                "Matched technical specification or scope signals.",
            ),
            (
                "eligibility_pqc",
                [
                    "pre qualification criteria",
                    "prequalification criteria",
                    "eligibility criteria",
                    "qualification criteria",
                    "minimum eligibility",
                    "bidder qualification",
                ],
                0.82,
                "Matched eligibility or qualification signals.",
            ),
            (
                "boq_or_price_schedule",
                [
                    "bill of quantities",
                    "price schedule",
                    "schedule of prices",
                    "financial bid format",
                    "boq",
                    "unit price",
                    "total quoted price",
                ],
                0.82,
                "Matched BOQ or price-schedule signals.",
            ),
            (
                "forms_annexures",
                [
                    "annexure",
                    "bid form",
                    "declaration format",
                    "undertaking format",
                    "form of agreement",
                    "checklist of documents",
                ],
                0.76,
                "Matched form or annexure signals.",
            ),
            (
                "contract_terms",
                [
                    "payment terms",
                    "delivery terms",
                    "liquidated damages",
                    "termination clause",
                    "governing law",
                    "dispute resolution",
                    "arbitration",
                ],
                0.76,
                "Matched contractual-term signals.",
            ),
            (
                "rfp_or_bid_document",
                [
                    "request for proposal",
                    "tender document",
                    "bid document",
                    "request for quotation",
                    "instructions to bidders",
                    "the bidder shall submit",
                ],
                0.75,
                "Matched general tender or RFP signals.",
            ),
        ]

        for (
            document_type,
            markers,
            confidence,
            reason,
        ) in rules:
            matched_signals = [
                marker
                for marker in markers
                if marker in haystack
            ]

            if matched_signals:
                return PageClassificationDecision(
                    page_id=page_id,
                    document_type=document_type,
                    content_role="tender_source",
                    title=self._page_title(
                        source_name=source_name,
                        page_number=page_number,
                        heading_lines=heading_lines,
                    ),
                    confidence=confidence,
                    reason=reason,
                    signals=matched_signals,
                    classification_method="deterministic_rules",
                )

        return PageClassificationDecision(
            page_id=page_id,
            document_type="unknown",
            content_role="tender_source",
            title=self._page_title(
                source_name=source_name,
                page_number=page_number,
                heading_lines=heading_lines,
            ),
            confidence=0.25,
            reason=(
                "No reliable deterministic classification "
                "signal was found."
            ),
            signals=[],
            classification_method="deterministic_fallback",
        )

    def summarize_document(
        self,
        *,
        document_id: UUID,
        decisions: list[PageClassificationDecision],
    ) -> DocumentClassificationDecision:
        if not decisions:
            return DocumentClassificationDecision(
                document_id=document_id,
                primary_document_type="unknown",
                content_role="unknown",
                confidence=0.0,
                needs_review=True,
                type_breakdown={},
            )

        type_counts = Counter(
            decision.document_type
            for decision in decisions
        )

        base_candidates = [
            decision
            for decision in decisions
            if decision.document_type
            in {
                "rfp_or_bid_document",
                "tender_notice",
                "gem_bid",
            }
        ]

        if base_candidates:
            primary_decision = max(
                base_candidates,
                key=lambda decision: decision.confidence,
            )
        else:
            primary_type = type_counts.most_common(1)[0][0]

            primary_decision = max(
                (
                    decision
                    for decision in decisions
                    if decision.document_type == primary_type
                ),
                key=lambda decision: decision.confidence,
            )

        average_confidence = sum(
            decision.confidence
            for decision in decisions
        ) / len(decisions)

        needs_review = any(
            decision.document_type == "unknown"
            or decision.confidence
            < self.limits.minimum_confidence
            for decision in decisions
        )

        return DocumentClassificationDecision(
            document_id=document_id,
            primary_document_type=(
                primary_decision.document_type
            ),
            content_role=primary_decision.content_role,
            confidence=round(average_confidence, 4),
            needs_review=needs_review,
            type_breakdown=dict(type_counts),
        )

    def _classify_strong_heading(
        self,
        *,
        heading_probe: str,
        page_id: UUID,
        page_number: int,
        source_name: str,
    ) -> PageClassificationDecision | None:
        strong_rules: list[
            tuple[TenderDocumentType, str, str]
        ] = [
            (
                "corrigendum",
                (
                    r"^(?:corrigendum|addendum|"
                    r"tender amendment|amendment to tender|"
                    r"amendment to rfp)\b"
                ),
                "Strong page heading identifies an amendment.",
            ),
            (
                "prebid_clarification",
                (
                    r"^(?:pre bid clarification|"
                    r"pre bid queries|"
                    r"reply to pre bid queries|"
                    r"response to pre bid queries)\b"
                ),
                (
                    "Strong page heading identifies a "
                    "pre-bid clarification."
                ),
            ),
            (
                "rfp_or_bid_document",
                (
                    r"^(?:request for proposal|"
                    r"tender document|bid document)\b"
                ),
                "Strong page heading identifies the base tender.",
            ),
            (
                "tender_notice",
                (
                    r"^(?:notice inviting tender|"
                    r"invitation for bids|"
                    r"invitation to tender)\b"
                ),
                "Strong page heading identifies a tender notice.",
            ),
        ]

        for document_type, pattern, reason in strong_rules:
            for line in heading_probe.splitlines():
                if re.match(pattern, line):
                    return PageClassificationDecision(
                        page_id=page_id,
                        document_type=document_type,
                        content_role="tender_source",
                        title=line[:500],
                        confidence=0.95,
                        reason=reason,
                        signals=[line],
                        classification_method=(
                            "deterministic_heading"
                        ),
                    )

        return None

    @staticmethod
    def _normalize(value: str) -> str:
        value = value.casefold()
        value = re.sub(r"[_/\\-]+", " ", value)
        value = re.sub(r"[^\w\s]", " ", value)
        return re.sub(r"\s+", " ", value).strip()

    @staticmethod
    def _page_title(
        *,
        source_name: str,
        page_number: int,
        heading_lines: list[str],
    ) -> str:
        if heading_lines:
            return heading_lines[0][:500]

        return f"{source_name} - page {page_number}"